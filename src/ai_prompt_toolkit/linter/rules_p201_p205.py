"""P201-P205 Prompt合规Lint规则

AI合规最佳实践(参考EU AI Act + 中国生成式AI管理办法 + GDPR):
- P201: 数据合规声明缺失(Prompt未声明数据处理合规性)
- P202: 用户同意机制缺失(未设置用户数据使用同意流程)
- P203: AI输出标识缺失(AI生成内容未标注"AI生成"标识)
- P204: 偏见公平声明缺失(未声明模型偏见缓解措施)
- P205: 数据留存策略缺失(未定义用户数据存储/删除策略)

覆盖OWASP LLM02(Sensitive Information), LLM07(Insecure Integration)
"""

from __future__ import annotations

import re

from ai_prompt_toolkit.linter.rules import _RULE_MAP, LintRule
from ai_prompt_toolkit.types import Finding, Severity

_RULES_P201_P205 = [
    LintRule(
        "P201",
        "数据合规声明缺失",
        "compliance",
        Severity.HIGH,
        "Prompt未声明数据处理合规性(如GDPR/个人信息保护法/数据安全法)",
        "添加合规声明: 如 'compliance: {gdpr: true, pipa: true, data_security_law: true}'",
        description_en="Prompt lacks data processing compliance declaration (GDPR/PIPA/Data Security Law)",
        remediation_en="Add compliance declaration: e.g. 'compliance: {gdpr: true, pipa: true, data_security_law: true}'",
        family="compliance_declaration",
        owasp_refs=["LLM02"],
    ),
    LintRule(
        "P202",
        "用户同意机制缺失",
        "compliance",
        Severity.HIGH,
        "Prompt未设置用户数据使用同意流程, 违反GDPR第6条合法依据要求",
        "添加同意机制: 如 'consent: {required: true, purpose: 数据分析, retention: 30d, withdraw: true}'",
        description_en="Prompt lacks user consent mechanism for data usage, violating GDPR Article 6 lawful basis",
        remediation_en="Add consent mechanism: e.g. 'consent: {required: true, purpose: data_analysis, retention: 30d}'",
        family="compliance_consent",
        owasp_refs=["LLM02"],
    ),
    LintRule(
        "P203",
        "AI输出标识缺失",
        "compliance",
        Severity.MEDIUM,
        "AI生成内容未标注'AI生成'标识, 违反EU AI Act第52条透明度义务",
        "添加AI标识: 如 'ai_generated: true, disclosure: 本内容由AI生成, 仅供参考'",
        description_en="AI-generated content lacks 'AI Generated' label, violating EU AI Act Article 52 transparency",
        remediation_en="Add AI label: e.g. 'ai_generated: true, disclosure: Content generated by AI, for reference only'",
        family="compliance_ai_label",
        owasp_refs=["LLM07"],
    ),
    LintRule(
        "P204",
        "偏见公平声明缺失",
        "compliance",
        Severity.MEDIUM,
        "Prompt未声明模型偏见缓解措施, 可能导致歧视性输出",
        "添加公平声明: 如 'fairness: {bias_audit: true, protected_groups: [性别,年龄,种族], mitigation: re-ranking}'",
        description_en="Prompt lacks bias/fairness declaration, may produce discriminatory output",
        remediation_en="Add fairness declaration: e.g. 'fairness: {bias_audit: true, protected_groups: [gender,age,race]}'",
        family="compliance_fairness",
        owasp_refs=["LLM07"],
    ),
    LintRule(
        "P205",
        "数据留存策略缺失",
        "compliance",
        Severity.HIGH,
        "未定义用户数据存储/删除策略, 违反GDPR第5条存储限制原则",
        "添加留存策略: 如 'data_retention: {max_days: 30, auto_delete: true, anonymize: true, audit_log: true}'",
        description_en="No data retention/deletion policy defined, violating GDPR Article 5 storage limitation",
        remediation_en="Add retention policy: e.g. 'data_retention: {max_days: 30, auto_delete: true, anonymize: true}'",
        family="compliance_retention",
        owasp_refs=["LLM02"],
    ),
]

for r in _RULES_P201_P205:
    _RULE_MAP[r.rule_id] = r

_COMPLIANCE_PATTERN = re.compile(r"(?:compliance|合规|gdpr|pipa|个人信息保护|数据安全法|data.security)", re.IGNORECASE)
_CONSENT_PATTERN = re.compile(r"(?:consent|同意|授权|许可|opt.in|用户授权)", re.IGNORECASE)
_AI_LABEL_PATTERN = re.compile(r"(?:ai.generated|AI生成|人工智能生成|generated.by.ai|本内容由AI)", re.IGNORECASE)
_FAIRNESS_PATTERN = re.compile(r"(?:fairness|公平|偏见|bias|discrimination|歧视|protected.groups)", re.IGNORECASE)
_RETENTION_PATTERN = re.compile(
    r"(?:retention|留存|保留|删除策略|auto.delete|anonymize|匿名化|max_days)", re.IGNORECASE
)
_DATA_PROCESSING_PATTERN = re.compile(
    r"(?:数据处理|data.processing|收集|collect|存储|store|用户数据|user.data)", re.IGNORECASE
)
# 否定式声明("不收集个人数据")不是数据处理事实 — 触发匹配前先剥离, 避免否定语盲区误报
_NEGATED_DATA_PATTERN = re.compile(
    r"(?:不|无需|不会|禁止|避免|不得|切勿)(?:收集|存储|采集|保存|保留|处理)[^，。;；,;]{0,12}"
    r"|(?:do(?:es)?\s+not|no|never)\s+(?:collect|store|retain|process)[^,.;]{0,20}",
    re.IGNORECASE,
)


def _strip_negated_data(text: str) -> str:
    return _NEGATED_DATA_PATTERN.sub("", text)


def check_p201(text: str) -> list[Finding]:
    findings = []
    has_data = _DATA_PROCESSING_PATTERN.search(_strip_negated_data(text))
    if has_data and not _COMPLIANCE_PATTERN.search(text):
        findings.append(Finding("P201", Severity.HIGH, "数据处理缺少合规声明", 1, 1))
    return findings


def check_p202(text: str) -> list[Finding]:
    findings = []
    has_data = _DATA_PROCESSING_PATTERN.search(_strip_negated_data(text))
    if has_data and not _CONSENT_PATTERN.search(text):
        findings.append(Finding("P202", Severity.HIGH, "用户数据使用缺少同意机制", 1, 1))
    return findings


def check_p203(text: str) -> list[Finding]:
    findings = []
    has_generate = re.search(r"(?:生成|generate|输出|output|produce)", text, re.IGNORECASE)
    if has_generate and not _AI_LABEL_PATTERN.search(text):
        findings.append(Finding("P203", Severity.MEDIUM, "AI生成内容缺少标识", 1, 1))
    return findings


def check_p204(text: str) -> list[Finding]:
    findings = []
    has_model = re.search(r"(?:模型|model|推理|inference|预测|predict)", text, re.IGNORECASE)
    if has_model and not _FAIRNESS_PATTERN.search(text):
        findings.append(Finding("P204", Severity.MEDIUM, "缺少偏见公平声明", 1, 1))
    return findings


def check_p205(text: str) -> list[Finding]:
    findings = []
    has_data = _DATA_PROCESSING_PATTERN.search(_strip_negated_data(text))
    if has_data and not _RETENTION_PATTERN.search(text):
        findings.append(Finding("P205", Severity.HIGH, "缺少数据留存策略", 1, 1))
    return findings
