_SEVERITY_FRIENDLY: dict[Severity, str] = {
    Severity.CRITICAL: "严重",
    Severity.HIGH: "重要",
    Severity.MEDIUM: "建议",
    Severity.LOW: "提示",
    Severity.INFO: "信息",
}


def translate_finding(finding: Finding) -> str:
    friendly = _FRIENDLY_DESCRIPTIONS.get(finding.rule_id)
    if not friendly:
        friendly = finding.description
    sev = _SEVERITY_FRIENDLY.get(finding.severity, "提示")
    return f"[{sev}] {friendly}"


def translate_findings(findings: list[Finding]) -> list[dict[str, str]]:
    return [
        {
            "rule_id": f.rule_id,
            "severity": f.severity.value,
            "friendly_description": _FRIENDLY_DESCRIPTIONS.get(f.rule_id, f.description),
            "remediation": f.remediation,
        }
        for f in findings
    ]
