"""Markdown报告生成器"""

from __future__ import annotations

from typing import Any


def generate_markdown_report(data: dict[str, Any]) -> str:
    lines = ["# AI Prompt Toolkit Report\n"]
    report_type = data.get("_report_type", "unknown")

    if report_type == "lint":
        _render_lint_md(data, lines)
    elif report_type == "scan":
        _render_scan_md(data, lines)
    elif report_type == "evaluate":
        _render_eval_md(data, lines)
    else:
        lines.append(f"Report type: {report_type}\n")
        for k, v in data.items():
            if not k.startswith("_"):
                lines.append(f"- **{k}**: {v}")

    lines.append("\n---\n*Generated by AI Prompt Toolkit*")
    return "\n".join(lines)


def _render_lint_md(data: dict[str, Any], lines: list[str]) -> None:
    target = data.get("lint_target", "unknown")
    lines.append(f"## Lint Report: `{target}`\n")

    findings = data.get("findings", [])
    total = len(findings)
    by_sev: dict[str, int] = {}
    for f in findings:
        sev = f.get("severity", "info")
        by_sev[sev] = by_sev.get(sev, 0) + 1

    lines.append(f"**Total findings**: {total}")
    if by_sev:
        sev_parts = [f"{k}: {v}" for k, v in sorted(by_sev.items())]
        lines.append(f"**By severity**: {', '.join(sev_parts)}")
    lines.append("")

    if findings:
        lines.append("| Rule | Severity | Description |")
        lines.append("|------|----------|-------------|")
        for f in findings:
            rid = f.get("rule_id", "")
            sev = f.get("severity", "info")
            desc = f.get("description", "").replace("|", "\\|")
            lines.append(f"| {rid} | {sev} | {desc} |")


def _render_scan_md(data: dict[str, Any], lines: list[str]) -> None:
    target = data.get("scan_target", "unknown")
    lines.append(f"## Security Scan Report: `{target}`\n")

    findings = data.get("findings", [])
    risk = data.get("risk_level", "unknown")
    lines.append(f"**Risk Level**: {risk}")
    lines.append(f"**Total findings**: {len(findings)}\n")

    if findings:
        lines.append("| Rule | Severity | Type | Description |")
        lines.append("|------|----------|------|-------------|")
        for f in findings:
            rid = f.get("rule_id", f.get("type", ""))
            sev = f.get("severity", "info")
            ftype = f.get("type", "")
            desc = f.get("description", "").replace("|", "\\|")
            lines.append(f"| {rid} | {sev} | {ftype} | {desc} |")


def _render_eval_md(data: dict[str, Any], lines: list[str]) -> None:
    lines.append("## Evaluation Report\n")
    reports = data.get("reports", [])
    for report in reports:
        tid = report.get("template_id", "unknown")
        lines.append(f"### {tid}\n")
        scores = report.get("scores", [])
        if scores:
            lines.append("| Dimension | Score |")
            lines.append("|-----------|-------|")
            for s in scores:
                dim = s.get("dimension_id", "")
                score = s.get("score", 0)
                lines.append(f"| {dim} | {score:.1f} |")
        lines.append("")
